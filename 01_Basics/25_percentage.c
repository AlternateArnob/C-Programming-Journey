// Example: Calculating percentage of 5 subjects

#include <stdio.h>

int main()
{
    float m1 = 100; // math
    float m2 = 77; // physics
    float m3 = 92; // chemistry
    float m4 = 90; // english
    float m5 = 86; // economics

    float p = (m1 + m2 + m3 + m4 + m5) / 5;
    // follows -> B O DM AS (operator precedence)

    printf("Percentage of 5 subjects is: %f", p);
    return 0;
}

// Output:
// Percentage of 5 subjects is: 89.000000

