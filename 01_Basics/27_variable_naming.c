// Area of a circle

#include <stdio.h>

int main()
{
    float radius = 5;
    float pi = 3.1416;
    float a = pi * radius * radius;
    printf("The area is: %f", a);
    return 0;
}

// Output:
// The area is: 78.539993

// // Instead of single letters like a, x, r we gave a full word like radius, pi.
// This is called variable naming.

