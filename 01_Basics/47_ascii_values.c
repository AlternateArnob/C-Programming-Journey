// ASCII Values

#include <stdio.h>

int main()
{
    char ch = 'a';
    printf("%c\n", ch); // a

    // ascii value of ch
    printf("%d\n\n", ch); // 97

    // --------------------------

    ch = 'A';
    printf("%d\n", ch); // 65

    ch = 'B';
    printf("%d\n", ch); // 66

    ch = 'C';
    printf("%d\n", ch); // 67

    // predict the output?
    ch = 'E';
    printf("%d\n", ch); // 69
    return 0;
}
